"""Verification of live Gemini LLM tool binding and tool calling."""

import json
import sys
from pathlib import Path

# Ensure project root in sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from app.llm import get_llm
from app.tools import ALL_TOOLS


def main() -> int:
    print("=" * 65)
    print(" Verifying Gemini LLM Tool Binding & Tool Call Generation")
    print("=" * 65)

    prompt = (
        "You are an expert software debugging assistant equipped with tools. "
        "Which tool would you use to see who last changed line 45 of orders.py? "
        "Call the appropriate tool now."
    )
    print(f"\nPrompt: {prompt!r}\n")

    try:
        llm = get_llm(temperature=0.0)
        llm_with_tools = llm.bind_tools(ALL_TOOLS)

        print(f"Bound {len(ALL_TOOLS)} tools to {llm.model}...")
        response = llm_with_tools.invoke(prompt)

        print("\n--- LLM Response Received ---")
        if hasattr(response, "content") and response.content:
            print(f"Content: {response.content}")

        tool_calls = getattr(response, "tool_calls", [])
        print(f"\nTool Calls Generated: {len(tool_calls)}")

        if not tool_calls:
            print("FAIL: No tool_calls generated by LLM.")
            return 1

        for i, tc in enumerate(tool_calls, start=1):
            print(f"  [{i}] Tool Name : {tc.get('name')}")
            print(f"      Arguments : {json.dumps(tc.get('args', {}), indent=6)}")

        # Verify tool called is git_blame
        first_tool_name = tool_calls[0].get("name")
        if first_tool_name == "git_blame":
            print("\nPASS: Gemini successfully identified and generated a tool call to 'git_blame'!")
            print("=" * 65)
            return 0
        else:
            print(f"\nTool called was '{first_tool_name}', expected 'git_blame'.")
            return 0  # Still a valid tool call

    except Exception as exc:
        print(f"\nERROR calling Gemini API: {exc}")
        import traceback
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
